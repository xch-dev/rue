use rue_diagnostic::{Applicability, Lint, Suggestion};
use rue_hir::{BinaryOp, Hir, HirId};

use crate::{
    HirLintPass, LintContext,
    equality::hir_eq,
    text::{negated_text_at, position, text_at},
};

/// Comparisons and operations between an expression and itself always have the same result.
#[derive(Debug, Default)]
pub(crate) struct SelfComparison;

impl HirLintPass for SelfComparison {
    fn lints(&self) -> &'static [Lint] {
        &[Lint::SelfComparison]
    }

    fn check_hir(&mut self, cx: &mut LintContext<'_>, hir: HirId, node: &Hir) {
        let Hir::Binary(op, left, right) = *node else {
            return;
        };

        let result = match op {
            BinaryOp::Eq
            | BinaryOp::Gte
            | BinaryOp::Lte
            | BinaryOp::GteBytes
            | BinaryOp::LteBytes => "always evaluates to `true`",
            BinaryOp::Ne | BinaryOp::Gt | BinaryOp::Lt | BinaryOp::GtBytes | BinaryOp::LtBytes => {
                "always evaluates to `false`"
            }
            BinaryOp::Sub | BinaryOp::BitwiseXor => "always evaluates to `0`",
            BinaryOp::BitwiseAnd | BinaryOp::BitwiseOr => "is the same as the value itself",
            _ => return,
        };

        let db = cx.db();

        // Nodes without a location were generated by the compiler, rather than written
        let (Some(srcloc), Some(_), Some(_)) = (
            db.hir_srcloc(hir),
            db.hir_srcloc(left),
            db.hir_srcloc(right),
        ) else {
            return;
        };

        if !hir_eq(db, left, right) {
            return;
        }

        let srcloc = srcloc.clone();

        cx.report(
            Lint::SelfComparison,
            srcloc,
            format!("Both sides of `{op}` are the same, so it {result}"),
        );
    }
}

/// Comparing a boolean with `true` or `false` is the same as the value or its negation.
#[derive(Debug, Default)]
pub(crate) struct BoolComparison;

impl HirLintPass for BoolComparison {
    fn lints(&self) -> &'static [Lint] {
        &[Lint::BoolComparison]
    }

    fn check_hir(&mut self, cx: &mut LintContext<'_>, hir: HirId, node: &Hir) {
        let Hir::Binary(op @ (BinaryOp::Eq | BinaryOp::Ne), left, right) = *node else {
            return;
        };

        let (value, literal) = match (bool_literal(cx, left), bool_literal(cx, right)) {
            (None, Some(literal)) => (left, literal),
            (Some(literal), None) => (right, literal),
            _ => return,
        };

        let Some(srcloc) = cx.db().hir_srcloc(hir).cloned() else {
            return;
        };

        // Only a boolean can be replaced by itself, since anything else (such as `nil`) can be
        // equal to neither `true` nor `false`
        let Some(ty) = cx.db().hir_type(value) else {
            return;
        };

        if !cx.is_assignable(ty, cx.builtin_types().bool) || cx.contains_unresolved(ty) {
            return;
        }

        let negate = (op == BinaryOp::Eq) != literal;

        // The value replaces the whole comparison, so it needs parentheses wherever the
        // comparison would have needed them
        let position = position(cx, hir);

        let replacement = if negate {
            negated_text_at(cx.db(), value, position)
        } else {
            text_at(cx.db(), value, position)
        };

        let Some(replacement) = replacement else {
            return;
        };

        let Some(diagnostic) = cx.report(
            Lint::BoolComparison,
            srcloc.clone(),
            format!("Unnecessary comparison with `{literal}`"),
        ) else {
            return;
        };

        diagnostic.suggestions.push(Suggestion::replace(
            if negate {
                "Negate the value instead"
            } else {
                "Use the value directly"
            },
            srcloc,
            replacement,
            Applicability::MachineApplicable,
        ));
    }
}

/// The value of a `true` or `false` literal that was written in the code.
fn bool_literal(cx: &LintContext<'_>, hir: HirId) -> Option<bool> {
    let db = cx.db();
    let hir = db.without_casts(hir);
    let srcloc = db.hir_srcloc(hir)?;

    match db.hir(hir) {
        Hir::Bool(value) if srcloc.text() == value.to_string() => Some(*value),
        _ => None,
    }
}
